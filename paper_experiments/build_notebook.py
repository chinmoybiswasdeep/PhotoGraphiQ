"""Build the manuscript notebook from the canonical experiment scripts.

The notebook has one section per experiment (R1-R60, in ``run_all_safe.SCRIPTS`` order). Each
section reproduces the script's own docstring and runs the unmodified script in a subprocess,
exactly as ``run_all_safe.py`` does, then shows the figures it wrote. Running scripts in
subprocesses keeps them isolated (argument parsing, ``__file__``, worker processes and
warnings behave as on the command line) and means the notebook can never drift from the
scripts: there is no copied code to keep in sync.

``TIERS`` in the first code cell selects what runs: ``{"smoke"}`` (minutes), ``{"smoke",
"safe"}`` (the default light run) or all three tiers with ``FULL = True`` for the publication
configuration. Regenerate after adding or renaming an experiment:

    python build_notebook.py
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

import nbformat as nbf

import run_all_safe

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "PhotoGraphiQ_Manuscript_Experiments.ipynb"
DOCSTRING_TITLE = re.compile(r"(.+?)\n\n(.*)", re.DOTALL)

SETUP = '''import json
import subprocess
import sys
import time
from pathlib import Path

from IPython.display import Image, Markdown, display

PAPER_EXPERIMENTS_DIR = Path.cwd()
if not (PAPER_EXPERIMENTS_DIR / "run_all_safe.py").exists():
    PAPER_EXPERIMENTS_DIR = Path("paper_experiments").resolve()
sys.path.insert(0, str(PAPER_EXPERIMENTS_DIR))
import run_all_safe  # noqa: E402  (the single source of tiers and optional dependencies)

TIERS = {"smoke", "safe"}  # add "heavy" (and set FULL = True) for the publication run
FULL = False
ENTRIES = {run_all_safe.experiment_id(e[0]): e for e in run_all_safe.SCRIPTS}
RECORD = {}


def run_experiment(rid):
    script, tier, needs, reason, accepts_full = ENTRIES[rid]
    import importlib.util

    missing = [m for m in needs if importlib.util.find_spec(m) is None]
    if tier not in TIERS:
        RECORD[rid] = "skipped"
        display(Markdown(f"*Skipped: tier `{tier}` not selected ({reason or 'see TIERS'}).*"))
        return
    if missing:
        RECORD[rid] = "skipped"
        display(Markdown(f"*Skipped: optional dependency missing: {', '.join(missing)}.*"))
        return
    path = PAPER_EXPERIMENTS_DIR / script
    command = [sys.executable, str(path)] + (["--full"] if FULL and accepts_full else [])
    start = time.perf_counter()
    done = subprocess.run(command, cwd=path.parent, capture_output=True, text=True)
    RECORD[rid] = "passed" if done.returncode == 0 else "FAILED"
    print(f"{rid}: {RECORD[rid]} in {time.perf_counter() - start:.1f} s")
    print(done.stdout[-3000:])
    if done.returncode != 0:
        print(done.stderr[-3000:])
        raise RuntimeError(f"{rid} failed its acceptance criteria; see the output above")
    for figure in sorted((PAPER_EXPERIMENTS_DIR / "figures" / "png").glob(f"{rid}_*.png")):
        display(Image(filename=str(figure), width=760))
'''


def docstring(path: Path) -> tuple[str, str]:
    doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or path.stem
    match = DOCSTRING_TITLE.match(doc)
    return (match.group(1).strip(), match.group(2).strip()) if match else (doc.strip(), "")


def main():
    cells = [
        nbf.v4.new_markdown_cell(
            "# PhotoGraphiQ manuscript experiment suite (R1-R60)\n\n"
            "Generated by `build_notebook.py` from the experiment scripts; do not edit by hand. "
            "Each section shows the script's docstring (question, model, reference, acceptance "
            "criteria), runs the unmodified script in a subprocess and displays the figures it "
            "wrote. Results, provenance and captions are written by the scripts themselves under "
            "`results/`, `figures/` and `figures/captions/`.\n\n"
            "Select what runs with `TIERS` in the setup cell: `{\"smoke\"}` takes minutes, "
            "`{\"smoke\", \"safe\"}` is the default light run, and adding `\"heavy\"` with "
            "`FULL = True` reproduces the publication configuration (hours; the timing studies "
            "should run on an otherwise idle machine). A missing optional dependency is reported "
            "as skipped, never as passed. See `EXPERIMENT_INDEX.md` and `STATUS.md`."
        ),
        nbf.v4.new_markdown_cell("## Install dependencies (once per environment)"),
        nbf.v4.new_code_cell(
            "# Core, development and autodiff extras from the local checkout (builds the native engines).\n"
            "import subprocess\nimport sys\n\n"
            "INSTALL = False  # set True on a fresh environment\n"
            "if INSTALL:\n"
            '    subprocess.run([sys.executable, "-m", "pip", "install", "-e", "..[dev,autodiff]"], check=True)\n'
        ),
        nbf.v4.new_markdown_cell("## Setup"),
        nbf.v4.new_code_cell(SETUP),
    ]
    for script, *_ in run_all_safe.SCRIPTS:
        rid = run_all_safe.experiment_id(script)
        title, body = docstring(ROOT / script)
        heading = title if title.startswith(rid) else f"{rid}: {title}"
        cells.append(nbf.v4.new_markdown_cell(f"## {heading}\n\nScript: `{script}`\n\n{body}"))
        cells.append(nbf.v4.new_code_cell(f'run_experiment("{rid}")'))
    cells.append(nbf.v4.new_markdown_cell("## Summary and manuscript tables"))
    cells.append(
        nbf.v4.new_code_cell(
            "print(json.dumps(RECORD, indent=1))\n"
            "import generate_tables  # noqa: E402\n\n"
            "generate_tables.main()\n"
        )
    )
    nb = nbf.v4.new_notebook(cells=cells)
    nb["metadata"] = {
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python", "pygments_lexer": "ipython3"},
    }
    nbf.validate(nb)
    OUTPUT.write_text(nbf.writes(nb), encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(cells)} cells)")


if __name__ == "__main__":
    main()
