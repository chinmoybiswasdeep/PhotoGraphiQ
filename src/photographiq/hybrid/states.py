"""Explicit Fock-state representation contracts and the Gaussian-to-Fock bridge.

Representation (:class:`FockRep`): a pure vector or a density matrix on the tensor product
of *per-mode* local dimensions (CUDA-Q's truncation; ``cudaq_dynamics.to_matrix`` order:
first mode most significant). PhotoGraphiQ's native Fock engines instead keep states with
*total* photon number < cutoff; :func:`to_total_photon` / :func:`from_total_photon` reuse
``cudaq_dynamics.per_mode_to_total_photon`` / ``total_photon_to_per_mode`` to move between
the two, reporting the truncation loss. States are never silently renormalised: every
projection multiplies ``retained_weight`` by the kept probability before an explicit
renormalisation, so the physical probability of the truncated part stays visible.

Gaussian-to-Fock bridge (hbar = 2, vacuum covariance I, interleaved (q, p)): a Gaussian state
(d, V) is prepared exactly as D(d) U_S rho_th U_S^dagger D(d)^dagger, where V = S diag(nu) S^T is
the Williamson decomposition and rho_th the product of thermal states with mean photon number
(nu - 1)/2. A symplectic S = expm(L) is generated by G = x^T A x / 2 with A = -Omega L / 2:
for U = exp(-i G), [x_j, x_k] = 2 i Omega_jk gives U^dagger x U = expm(2 Omega A) x = S x. S is
split into a symmetric positive and an orthogonal (passive) symplectic factor (polar
decomposition), each with a real logarithm. The generator is exponentiated on an enlarged
per-mode space (``pad`` extra levels) and the result projected onto the requested dimensions.
Moment-matched Fock-to-Gaussian conversion is offered only as an explicitly approximate,
labelled operation (:func:`moment_matched_gaussian`).
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace
from math import prod

import numpy as np
from scipy.linalg import expm, logm, polar, schur, sqrtm

from .. import cudaq_dynamics as cq
from ..gaussian import omega

REPRESENTATIONS = ("pure-fock", "mixed-fock")


@dataclass(frozen=True)
class FockRep:
    """Truncated Fock state on per-mode local dimensions.

    ``data`` has shape (D,) (pure) or (D, D) (mixed), D = prod(dims). ``retained_weight`` is
    the product of every truncation/projection probability applied so far (the state itself
    is normalised); ``physical_parameters`` and ``history`` record how it was produced.
    """

    data: np.ndarray
    modes: tuple
    dims: tuple
    retained_weight: float = 1.0
    physical_parameters: dict = field(default_factory=dict)
    precision: str = "complex128"

    def __post_init__(self):
        D = prod(self.dims)
        data = np.asarray(self.data, dtype=complex)
        if len(self.modes) != len(self.dims) or len(set(self.modes)) != len(self.modes):
            raise ValueError("One unique mode label per local dimension")
        if data.shape not in ((D,), (D, D)):
            raise ValueError(f"Fock data must have shape ({D},) or ({D}, {D})")
        object.__setattr__(self, "data", data)

    @property
    def representation(self) -> str:
        return "pure-fock" if self.data.ndim == 1 else "mixed-fock"

    @property
    def normalization(self) -> float:
        return float(
            np.vdot(self.data, self.data).real if self.data.ndim == 1 else np.trace(self.data).real
        )

    def contract(self) -> dict:
        """The representation contract fields (mode order, dimensions, weights, ...)."""
        return {
            "mode_order": list(self.modes),
            "hilbert_space_dimensions": list(self.dims),
            "total_photon_cutoff": None,
            "representation_type": self.representation,
            "normalization": self.normalization,
            "retained_weight": self.retained_weight,
            "physical_parameters": dict(self.physical_parameters),
            "numerical_precision": self.precision,
        }

    def boundary_population(self, levels=2) -> float:
        """Max over modes of the probability with n_k >= d_k - levels (the native backends'
        truncation diagnostic, per mode). Truncated-generator gates are norm preserving, so this,
        not the norm, is what flags an insufficient local dimension."""
        p = (np.abs(self.data) ** 2 if self.data.ndim == 1 else np.diag(self.data).real).reshape(
            self.dims
        )
        return float(
            max(np.moveaxis(p, k, 0)[max(1, d - levels) :].sum() for k, d in enumerate(self.dims))
        )

    def density_matrix(self) -> np.ndarray:
        return np.outer(self.data, self.data.conj()) if self.data.ndim == 1 else self.data

    def to_mixed(self) -> FockRep:
        return self if self.data.ndim == 2 else replace(self, data=self.density_matrix())

    def tensor(self, other: FockRep) -> FockRep:
        if set(self.modes) & set(other.modes):
            raise ValueError("Tensor product needs disjoint mode labels")
        if self.data.ndim == other.data.ndim == 1:
            data = np.kron(self.data, other.data)
        else:
            data = np.kron(self.density_matrix(), other.density_matrix())
        return FockRep(
            data,
            self.modes + other.modes,
            self.dims + other.dims,
            self.retained_weight * other.retained_weight,
            {**self.physical_parameters, **other.physical_parameters},
            self.precision,
        )

    def reduced(self, modes) -> FockRep:
        """Partial trace onto ``modes`` (in the given order)."""
        modes = tuple(modes)
        keep = [self.modes.index(m) for m in modes]
        d = prod(self.dims[i] for i in keep)
        n = len(self.dims)
        if self.data.ndim == 1:  # never form the full density matrix of a pure state
            t = np.moveaxis(self.data.reshape(self.dims), keep, list(range(len(keep)))).reshape(
                d, -1
            )
            return FockRep(
                t @ t.conj().T,
                modes,
                tuple(self.dims[i] for i in keep),
                self.retained_weight,
                dict(self.physical_parameters),
                self.precision,
            )
        rho = self.data.reshape(self.dims + self.dims)
        drop = [i for i in range(n) if i not in keep]
        letters = "abcdefghijklmnopqrstuvwxyz"
        row = [letters[i] for i in range(n)]
        col = [letters[i].upper() for i in range(n)]
        for i in drop:
            col[i] = row[i]
        out_row = "".join(row[i] for i in keep)
        out_col = "".join(col[i] for i in keep)
        rho = np.einsum(f"{''.join(row)}{''.join(col)}->{out_row}{out_col}", rho)
        return FockRep(
            rho.reshape(d, d),
            modes,
            tuple(self.dims[i] for i in keep),
            self.retained_weight,
            dict(self.physical_parameters),
            self.precision,
        )

    # moments (hbar = 2) -------------------------------------------------------------
    def _ops(self, k):
        d = self.dims[k]
        a = np.diag(np.sqrt(np.arange(1, d)), 1).astype(complex)
        return a + a.conj().T, -1j * (a - a.conj().T)

    def _embed(self, k, op):
        mats: list[np.ndarray] = [np.eye(d) for d in self.dims]
        mats[k] = op
        out = mats[0]
        for m in mats[1:]:
            out = np.kron(out, m)
        return out

    def moments(self):
        """(mean, covariance) of the interleaved quadratures of the truncated state."""
        rho = self.density_matrix()
        ops = []
        for k in range(len(self.dims)):
            q, p = self._ops(k)
            ops += [self._embed(k, q), self._embed(k, p)]
        mean = np.array([np.trace(o @ rho).real for o in ops])
        n = len(ops)
        cov = np.empty((n, n))
        for i in range(n):
            for j in range(i, n):
                sym = (ops[i] @ ops[j] + ops[j] @ ops[i]) / 2
                cov[i, j] = cov[j, i] = np.trace(sym @ rho).real - mean[i] * mean[j]
        return mean, cov


# ---------------------------------------------------------------------------- mappings
def to_total_photon(rep: FockRep, cutoff: int) -> tuple[np.ndarray, float]:
    """Native-order total-photon state (not renormalised) and its retained weight."""
    dims = {k: d for k, d in enumerate(rep.dims)}
    data = cq.per_mode_to_total_photon(rep.data, dims, cutoff)
    weight = float(np.vdot(data, data).real if data.ndim == 1 else np.trace(data).real)
    return data, weight


def from_total_photon(data, modes, dims, cutoff, **kw) -> FockRep:
    """Embed a native total-photon state into per-mode dimensions (exact when dims >= cutoff)."""
    d = {k: int(x) for k, x in enumerate(dims)}
    return FockRep(
        cq.total_photon_to_per_mode(np.asarray(data), d, cutoff), tuple(modes), tuple(dims), **kw
    )


# ---------------------------------------------------------------------------- Gaussian bridge
def _xxpp(n):
    return np.r_[0 : 2 * n : 2, 1 : 2 * n : 2]


def williamson(V, tol=1e-10):
    """(nu, S) with V = S diag(nu_1, nu_1, ..., nu_n, nu_n) S^T, S symplectic (interleaved).

    K = V^{-1/2} Omega V^{-1/2} is real antisymmetric; its real Schur form Q^T K Q is block
    diagonal with blocks [[0, 1/nu], [-1/nu, 0]] (orientation fixed by swapping columns).
    T = D^{1/2} Q^T V^{-1/2} then satisfies T V T^T = D and T Omega T^T = Omega, so S = T^{-1}.
    """
    V = np.asarray(V, float)
    n = len(V) // 2
    if np.linalg.eigvalsh(V).min() <= 0:
        raise ValueError("Covariance must be positive definite")
    half = np.real(sqrtm(V))
    inv_half = np.linalg.inv(half)
    K = inv_half @ omega(n) @ inv_half
    T, Q = schur((K - K.T) / 2, output="real")
    for i in range(n):  # orient each block as [[0, +b], [-b, 0]]
        if T[2 * i, 2 * i + 1] < 0:
            Q[:, [2 * i, 2 * i + 1]] = Q[:, [2 * i + 1, 2 * i]]
    blocks = Q.T @ K @ Q
    nu = np.array([1 / blocks[2 * i, 2 * i + 1] for i in range(n)])
    S = half @ Q @ np.diag(np.repeat(1 / np.sqrt(nu), 2))  # = T^{-1}
    recon = S @ np.diag(np.repeat(nu, 2)) @ S.T
    if not np.allclose(recon, V, atol=tol * max(1, np.abs(V).max())) or not np.allclose(
        S @ omega(n) @ S.T, omega(n), atol=1e-8 * max(1, np.abs(S).max() ** 2)
    ):
        raise ArithmeticError("Williamson decomposition failed")
    return nu, S


def _generator(L, modes):
    """Quadratic Hamiltonian G with exp(-i G) realising Heisenberg x -> expm(L) x."""
    n = len(L) // 2
    A = -0.5 * omega(n) @ L
    A = (A + A.T) / 2
    xs = []
    for m in modes:
        xs += [cq.position(m), cq.momentum(m)]
    G = cq.BosonicHamiltonian()
    for i in range(2 * n):
        for j in range(2 * n):
            if abs(A[i, j]) > 1e-15:
                G = G + 0.5 * A[i, j] * xs[i] * xs[j]
    return G


def _apply_unitary_generator(rho_or_psi, G, dims):
    from scipy.sparse import csr_array
    from scipy.sparse.linalg import expm_multiply

    H = csr_array(cq.to_matrix(G, {k: d for k, d in enumerate(dims)}))
    if rho_or_psi.ndim == 1:
        return expm_multiply(-1j * H, rho_or_psi)
    U = expm(-1j * H.toarray())
    return U @ rho_or_psi @ U.conj().T


def gaussian_to_fock(mean, covariance, dims, *, modes=None, pad=None, pure_tol=1e-9) -> FockRep:
    """Fock representation of the Gaussian state (mean, covariance) on per-mode ``dims``.

    Pure states (all symplectic eigenvalues 1) give a vector; mixed states a density matrix
    (thermal product transformed by U_S and D). The construction runs on dims + pad levels per
    mode and is projected onto ``dims``; the kept probability is ``retained_weight``.
    """
    mean, V = np.asarray(mean, float), np.asarray(covariance, float)
    n = len(mean) // 2
    dims = tuple(int(d) for d in dims)
    if len(dims) != n or V.shape != (2 * n, 2 * n):
        raise ValueError("dims, mean and covariance sizes disagree")
    if np.linalg.eigvalsh(V + 1j * omega(n)).min() < -1e-9:
        raise ValueError("Covariance violates the uncertainty principle")
    modes = tuple(range(n)) if modes is None else tuple(modes)
    pad = max(dims) if pad is None else int(pad)
    big = tuple(d + pad for d in dims)
    nu, S = williamson(V)
    pure = bool(np.all(np.abs(nu - 1) < pure_tol))
    if pure:
        state = np.zeros(prod(big), complex)
        state[0] = 1.0
    else:
        diag = np.array([1.0])
        for k in range(n):
            nbar = (nu[k] - 1) / 2
            levels = np.arange(big[k])
            th = nbar**levels / (1 + nbar) ** (levels + 1)
            diag = np.kron(diag, th)
        state = np.diag(diag).astype(complex)
    Q, P = polar(S, side="left")  # S = P Q (scipy returns (u, p)), P sym. positive, Q orthogonal
    local = tuple(range(n))
    for factor in (Q, P):  # Heisenberg: rho -> U_Q first, then U_P  (S = P Q)
        if np.allclose(factor, np.eye(2 * n), atol=1e-14):
            continue
        L = logm(factor)
        if np.abs(L.imag).max() > 1e-9:
            raise NotImplementedError("Symplectic factor without a real logarithm (eigenvalue -1)")
        state = _apply_unitary_generator(state, _generator(L.real, local), big)
    D = cq.BosonicHamiltonian()
    for k in range(n):
        D = D + cq.displacement(k, mean[2 * k], mean[2 * k + 1])
    if np.any(mean != 0):
        state = _apply_unitary_generator(state, D, big)
    # project onto the requested per-mode dimensions
    keep = np.ix_(*[np.arange(d) for d in dims])
    if state.ndim == 1:
        t = state.reshape(big)[keep].reshape(-1)
        weight = float(np.vdot(t, t).real)
        data = t / np.sqrt(weight)
    else:
        both = np.ix_(*[np.arange(d) for d in dims * 2])
        t = state.reshape(big + big)[both].reshape(prod(dims), prod(dims))
        weight = float(np.trace(t).real)
        data = t / weight
    return FockRep(
        data,
        modes,
        dims,
        weight,
        {
            "source": "gaussian",
            "mean": mean.tolist(),
            "symplectic_eigenvalues": nu.tolist(),
            "pad": pad,
        },
    )


def moment_matched_gaussian(rep: FockRep):
    """(mean, covariance) of a Fock state, labelled as an APPROXIMATE Gaussian projection.

    Returns a dict with ``approximate: True``; it is exact only if the state is Gaussian.
    """
    mean, cov = rep.moments()
    return {
        "mean": mean,
        "covariance": cov,
        "approximate": True,
        "note": "moment-matched Gaussian projection; exact only for Gaussian states",
    }


def fock_input(amplitudes, mode, dim) -> FockRep:
    """Single-mode Fock superposition, truncated to ``dim`` levels (weight recorded)."""
    amps = np.zeros(dim, complex)
    a = np.asarray(amplitudes, complex)
    amps[: min(dim, len(a))] = a[:dim]
    total = float(np.vdot(a, a).real)
    kept = float(np.vdot(amps, amps).real)
    if kept <= 0:
        raise ValueError("Fock input has no weight below the local dimension")
    return FockRep(amps / np.sqrt(kept), (mode,), (dim,), kept / total, {"source": "fock"})
